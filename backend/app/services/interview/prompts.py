"""Prompt templates with strict input sanitization and structured schemas."""

from pydantic import BaseModel, Field
from app.schemas import CamelModel, RubricScores, BlueprintTopic, StudyPlanItem, CodingProblem


# -----------------------------------------------------------------------------
# Decision Schemas
# -----------------------------------------------------------------------------


class TurnEvaluation(CamelModel):
    scores: RubricScores
    strengths: list[str] = Field(description="Max 3 concise positive points")
    improvements: list[str] = Field(description="Max 3 specific, constructive tips")
    missing_concepts: list[str] = Field(description="Core expected concepts not mentioned or incorrect")
    concepts_covered: list[str] = Field(description="Expected concepts correctly covered")


class TurnDecisionAction(CamelModel):
    action: str = Field(description="'follow_up', 'next_topic', or 'finish'")
    reason: str


class NextQuestionOutput(CamelModel):
    text: str = Field(description="Spoken question, max 35 words, no code or markdown")
    topic: str
    expected_concepts: list[str] = Field(description="3 to 5 core concepts for the next answer")


class TurnDecision(CamelModel):
    evaluation: TurnEvaluation
    decision: TurnDecisionAction
    next_question: NextQuestionOutput | None = None


class ModelAnswerItem(CamelModel):
    question_id: str
    model_answer: str = Field(description="Concise model answer <=90 words")


class ReportNarrative(CamelModel):
    strengths: list[str] = Field(description="3-5 top overall strengths")
    weaknesses: list[str] = Field(description="3-5 overall improvement areas")
    summary_feedback: str = Field(description="60-90 words, warm and spoken-friendly")
    study_plan: list[StudyPlanItem]
    model_answers: list[ModelAnswerItem]


class CodingProblemOutput(CodingProblem):
    """Structured coding prompt generated by the interviewer."""

    id: str = ""


class CodingApproachOutput(CamelModel):
    scores: RubricScores
    strengths: list[str]
    improvements: list[str]
    missing_concepts: list[str]
    follow_up_question: str | None = None


class CodingReviewOutput(CamelModel):
    scores: RubricScores
    strengths: list[str]
    improvements: list[str]
    missing_concepts: list[str]
    correctness_summary: str
    time_complexity: str
    space_complexity: str
    review: str


